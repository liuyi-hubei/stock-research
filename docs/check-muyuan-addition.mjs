import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const c=vm.createContext({window:{}});
for(const f of ['assets/shareholder-model.js','data/stocks.js','data/additional-stocks.js'])vm.runInContext(fs.readFileSync(path.join(root,f),'utf8'),c);
const matches=c.window.STOCK_RESEARCH.stocks.filter(s=>s.code==='002714');
assert.equal(matches.length,1);
const s=matches[0],m=s.model,engine=c.window.ShareholderModel,r=engine.evaluate(s);
assert(s.market.includes('A股') && m.currency==='元');
assert.equal(s.masterViews.length,5);
assert.equal(new Set(s.masterViews.map(v=>v.text)).size,5);
assert(s.shareCount>5.7e9);
assert(m.financialAsOf && m.rankingDecision.reviewedAt && m.parameterReview.references.length>=4);
assert.equal(engine.eligibility(s,r).eligible,false);
assert.equal(m.status,'pending');
assert.equal(engine.isPending(s),true);
assert.equal(r,null);
assert.equal(engine.sensitivity(s),null);
assert.equal(m.requiredReturn,null);
for(const values of [m.assumptions,s.assumptions,s.profitForecast.scenarios])assert(Array.isArray(values) && values.length===0,'Pending assumptions must be explicitly empty');
assert(!engine.ranked(c.window.STOCK_RESEARCH.stocks).some(row=>row.stock.code===s.code));
const scripts=['index.html','reports.html','stock.html','industry.html'].map(f=>fs.readFileSync(path.join(root,f),'utf8').match(/additional-stocks\.js\?v=([^"\s]+)/)?.[1]);
assert(scripts.every(v=>v && v===scripts[0]));
for(const suffix of ['','-数据核验'])assert(fs.existsSync(path.join(root,`reports/stocks/${s.name}-${s.code}${suffix}.md`)));
console.log('PASS: Muyuan A-share/CNY, total ordinary shares, explicit pending without numerical scenarios, excluded ranking and five views. Not a financial audit.');
