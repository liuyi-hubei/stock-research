import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const c=vm.createContext({window:{}});
for(const f of ['assets/shareholder-model.js','data/stocks.js','data/additional-stocks.js'])vm.runInContext(fs.readFileSync(path.join(root,f),'utf8'),c);
const rows=c.window.STOCK_RESEARCH.stocks.filter(s=>s.code==='688825');
assert.equal(rows.length,1);
const s=rows[0], m=s.model, engine=c.window.ShareholderModel, r=engine.evaluate(s);
assert(s.market.includes('A股') && m.currency==='元');
assert.equal(m.financialAsOf,'2026-06-30');
assert.equal(m.rankingDecision.eligible,false);
assert.equal(engine.eligibility(s,r).eligible,false);
assert.equal(s.masterViews.length,5);
assert.equal(new Set(s.masterViews.map(v=>v.text)).size,5);
assert(m.parameterReview.references.length>=5);
assert(s.shareCount>6e10);
assert.equal(m.status,'pending');
assert.equal(engine.isPending(s),true);
assert.equal(r,null);
assert.equal(engine.sensitivity(s),null);
assert.equal(m.requiredReturn,null);
for(const values of [m.assumptions,s.assumptions,s.profitForecast.scenarios])assert(Array.isArray(values) && values.length===0,'Pending assumptions must be explicitly empty');
assert(!engine.ranked(c.window.STOCK_RESEARCH.stocks).some(row=>row.stock.code===s.code));
for(const suffix of ['','-数据核验'])assert(fs.existsSync(path.join(root,`reports/stocks/${s.name}-${s.code}${suffix}.md`)));
const cacheVersions=['index.html','stock.html','reports.html','industry.html'].map(f=>fs.readFileSync(path.join(root,f),'utf8').match(/additional-stocks\.js\?v=([^"\s]+)/)?.[1]);
assert(cacheVersions.every(v=>v && v===cacheVersions[0]));
console.log('PASS: CXMT unique A-share, post-IPO share basis, actual/report distinction, explicit pending without numerical scenarios, excluded from ranking. Not a financial audit.');
