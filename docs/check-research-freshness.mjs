import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
const root=fileURLToPath(new URL('../',import.meta.url));
const c=vm.createContext({window:{},Intl});
vm.runInContext(fs.readFileSync(root+'assets/research-freshness.js','utf8'),c);
const f=c.window.ResearchFreshness;
const sample={priceDate:'2026-09-30',researchDate:'2026-10-01',model:{financialPeriod:'2026H1',reviewedAt:'2026-09-29'}};
assert.equal(f.assess(sample,'2026-10-01').state,'recent');
assert.equal(f.assess(sample,'2026-10-30').state,'recent');
assert.equal(f.assess(sample,'2026-10-31').state,'review');
assert.equal(f.assess({...sample,priceDate:'2026-10-02'},'2026-10-01').state,'unknown');
assert.equal(f.assess({...sample,priceDate:'2026-02-30'},'2026-10-01').priceAge,null);
assert.equal(f.age('2024-02-29','2024-03-01'),1);
assert.equal(f.age('2025-02-29','2025-03-01'),null);
assert.equal(f.financialEnd('FY2027 Q1'),null);
assert.equal(f.financialEnd('FY2026（2025-04-01至2026-03-31）；FY2027 Q1（2026-04-01至2026-06-30）'),'2026-06-30');
assert.equal(f.financialEnd('2026H1'),'2026-06-30');
const old={...sample,researchDate:'2026-06-01',model:{...sample.model,parameterReview:{reviewedAt:'2026-10-01'}}};
assert.equal(f.assess(old,'2026-10-01').state,'review');
assert.equal(f.assess(old,'2026-10-01').reviewDate,'2026-06-01');
assert.equal(f.assess({model:{}},'2026-10-01').state,'unknown');
const fallback={...sample,researchDate:undefined};
assert.equal(f.assess(fallback,'2026-10-01').reviewLabel,'模型记录');
const saved=JSON.stringify(sample);
f.assess(sample,'2027-10-01');
assert.equal(JSON.stringify(sample),saved,'Freshness must not modify research data');
console.log('PASS: Shanghai calendar dates, boundary thresholds, missing/future dates, fiscal periods and non-mutating freshness.');
