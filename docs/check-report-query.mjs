import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
const root=fileURLToPath(new URL('../',import.meta.url));
const c=vm.createContext({window:{},Intl});
for(const file of ['assets/research-freshness.js','assets/report-query.js','assets/shareholder-model.js','data/stocks.js','data/additional-stocks.js'])vm.runInContext(fs.readFileSync(root+file,'utf8'),c);
const {ReportQuery:q,STOCK_RESEARCH:db}=c.window;
const saved=JSON.stringify(db.stocks);
assert.equal(q.filter(db.stocks,{}).length,db.stocks.length);
assert.equal(q.filter(db.stocks,{q:'分众'}).length,1);
assert.equal(q.filter(db.stocks,{q:'００２０２７'}).length,1);
assert.equal(q.filter(db.stocks,{q:'  分众 002027 '}).length,1);
assert.equal(q.filter(db.stocks,{q:'不存在的报告'}).length,0);
const focus=db.stocks.find(s=>s.code==='002027');
assert.equal(q.filter(db.stocks,{q:'分众',market:'港股'}).length,0);
assert.equal(q.filter(db.stocks,{q:'分众',market:'A股',industry:focus.industry,evidence:q.evidence(focus),freshness:'recent'},'2026-10-01').length,1);
assert.equal(q.filter(db.stocks,{q:'分众',freshness:'review'},'2027-10-01').length,1);
assert(q.filter(db.stocks,{market:'港股'}).every(s=>s.market.includes('港股')));
assert.equal(q.evidence({model:{}}),'未标注');
assert.equal(JSON.stringify(db.stocks),saved,'Filters must not alter research data');
console.log('PASS: normalized keywords, market/industry/evidence/freshness intersection, empty results and unchanged source data.');
